"""Collect every stage's outputs into RESULTS.md (safe to run at any time; skips missing stages)."""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
L = ["# Results (auto-generated by scripts/99_summarize.py)\n"]


def img(p):
    return f"![{p.stem}]({p.relative_to(ROOT).as_posix()})\n" if p.exists() else ""


# ---- stage 0
s0 = R / "00_behaviour" / "summary.md"
if s0.exists():
    L.append("## Stage 0 — behaviour\n")
    txt = s0.read_text().split("## Contrast 1", 1)
    L.append("## Contrast 1" + txt[1] if len(txt) > 1 else txt[0])
    for p in ["c1_delta_bare.png", "c1_delta_ctx.png", "c2_delta.png"]:
        L.append(img(R / "00_behaviour" / p))

# ---- stage 1
for d in sorted((R / "01_lens_dla").glob("*")) if (R / "01_lens_dla").exists() else []:
    info = json.loads((d / "info.json").read_text()) if (d / "info.json").exists() else {}
    L.append(f"## Stage 1 — logit lens + DLA: {d.name}\n")
    L.append(f"- n={info.get('n')}; DLA reconstruction rel. error={info.get('dla_reconstruction_rel_err', float('nan')):.2e}\n"
             f"- final lens gap (A−B) = {info.get('lens_gap_final', float('nan')):.2f}; first layer where gap > ½ final: "
             f"{info.get('lens_first_layer_gap_over_half_final')}\n"
             f"- top components (differential DLA): {', '.join(f'{c} {v:+.2f}' for c, v in info.get('top_components', []))}\n"
             f"- top heads (layer, head, diff): {', '.join(f'L{int(l)}H{int(h)} {v:+.2f}' for l, h, v in info.get('top_heads', []))}\n")
    for p in ["logit_lens.png", "latent_lens.png", "dla.png"]:
        L.append(img(d / p))

# ---- stage 2
for d in sorted((R / "02_patching").glob("*")) if (R / "02_patching").exists() else []:
    if d.name.endswith("_smoke"):
        continue
    info = json.loads((d / "info.json").read_text()) if (d / "info.json").exists() else {}
    L.append(f"## Stage 2 — activation patching: {d.name}\n")
    L.append(f"- pairs used {info.get('n_used')} (of {info.get('n_candidate_pairs')}, {info.get('n_correct')} correct both ways); "
             f"Δ_clean {info.get('d_clean')}, Δ_corrupt {info.get('d_corr')}\n"
             f"- example: `{info.get('example_clean')}` vs `{info.get('example_corrupt')}`; roles {info.get('example_roles')}\n"
             f"- sanity: full layer-0 patch err {info.get('sanity_full_layer0_patch_maxabs_err')}, identity err "
             f"{info.get('sanity_identity_patch_maxabs_err')}\n")
    for kind in ["resid_pre", "attn_out", "mlp_out"]:
        f = d / f"act_{kind}.csv"
        if f.exists():
            df = pd.read_csv(f)
            top = df.reindex(df.R.abs().sort_values(ascending=False).index).head(6)
            L.append(f"- {kind} top sites: " + ", ".join(
                f"L{r.layer}/{r.role} R={r.R:.2f} [{r.R_lo:.2f},{r.R_hi:.2f}]" for r in top.itertuples()) + "\n")
    f = d / "act_heads.csv"
    if f.exists():
        df = pd.read_csv(f)
        top = df.reindex(df.R.abs().sort_values(ascending=False).index).head(8)
        L.append("- heads top: " + ", ".join(f"L{r.layer}H{int(r.head)}/{r.role} R={r.R:.2f}" for r in top.itertuples()) + "\n")
    for p in ["attr_resid_pre.png", "act_resid_pre.png", "act_attn_out.png", "act_mlp_out.png", "act_heads.png"]:
        L.append(img(d / p))

# ---- stage 3
f = R / "03_probe_gender" / "probe_gender.csv"
if f.exists():
    df = pd.read_csv(f)
    L.append("## Stage 3a — noun-gender probes (templates)\n")
    for pos in ["noun", "final"]:
        d = df[df.position == pos]
        for lang in ["hi", "pa", "en", "ta"]:
            e = d[d.lang == lang]
            b = e.loc[e.selectivity.idxmax()]
            line = f"- [{pos}] {lang}: best selectivity {b.selectivity:.2f} at layer {int(b.layer)} (acc {b.acc:.2f}, control {b.control:.2f})"
            if lang != "hi":
                t = e.loc[e.transfer_from_hi.idxmax()]
                line += f"; hi→{lang} transfer max {t.transfer_from_hi:.2f} at layer {int(t.layer)} (shuffled {t.shuffled_transfer:.2f}, cos {t.cos_with_hi:.2f})"
            L.append(line + "\n")
    L.append(img(R / "03_probe_gender" / "probe_gender.png"))
f = R / "03_probe_case" / "probe_case.csv"
if f.exists():
    L.append("## Stage 3b — treebank case probes\n")
    for p in sorted((R / "03_probe_case").glob("*.png")):
        L.append(img(p))

# ---- stage 4
f = R / "04_sae" / "sae_sharing_steering.csv"
if f.exists():
    L.append("## Stage 4 — SAE features\n")
    L.append(pd.read_csv(f).round(3).to_markdown(index=False) + "\n")
    rc = R / "04_sae" / "sae_recon.csv"
    if rc.exists():
        L.append(pd.read_csv(rc).round(3).to_markdown(index=False) + "\n")
    L.append(img(R / "04_sae" / "sae_sharing.png"))

(ROOT / "RESULTS.md").write_text("\n".join(L))
print("wrote RESULTS.md")
